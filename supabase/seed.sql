      when n <= 40 then ((n - 30) - 3)::text
      else 'a÷' || (n - 40)
    end as choice_c,
    case
      when n <= 10 then (n + 6)::text
      when n <= 20 then ((n - 25) * -2 + 1)::text
      when n <= 30 then '0 と ' || (n - 20)::text
      when n <= 40 then (2 * (n - 30))::text
      else 'a-' || (n - 40)

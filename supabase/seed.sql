  select 'math' as subject_en,
    case
      when n <= 10 then '正負の数（加減）'
      when n <= 20 then '正負の数（乗除）'
      when n <= 30 then '絶対値'
      when n <= 40 then '文字式の代入'
      else '文字式の表し方'
    end as category,
    case
      when n <= 10 then '(' || (n - 6) || ') + (' || (-n) || ') を計算しなさい。'
      when n <= 20 then '(' || (n - 25) || ') × (-2) を計算しなさい。'
      when n <= 30 then '絶対値が ' || (n - 20) || ' である数の組み合わせとして正しいものはどれですか。'

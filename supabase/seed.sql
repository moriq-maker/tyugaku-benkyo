      when n <= 10 then ((n - 6) - n - 1)::text
      when n <= 20 then ((25 - n) * 2)::text
      when n <= 30 then '-' || (n - 20)::text || 'だけ'
      when n <= 40 then (2 * (n - 30) - 3)::text
      else (n - 40)::text || 'a'
